def expand_syllables() -> list[str]:
    from src.vni import apply_tone, letters_in_text

    words: list[str] = []
    for stem, tones in STEMS:
        base = "".join(letters_in_text(stem))
        if not base or " " in base:
            continue
        for mark in tones:
            words.append(apply_tone(base, int(mark)))
    return words
